local function showModelFromTemplate(template, pose)
    clearViewport()

    if not template then
        return false
    end

    local success, clone = pcall(function()
        return template:Clone()
    end)

    if not success or not clone then
        return false
    end

    removeExtraObjects(clone)
    clone.Parent = World
    currentModel = clone

    resetJoints(clone)
    rememberJointBases(clone)

    if not centerModel(clone) then
        clone:Destroy()
        currentModel = nil
        return false
    end

    applyPose(clone, pose or "N")
    return true
end

local function showPlayerModel(player)
    clearViewport()

    local clone = makeStaticAvatar(player)

    if not clone then
        task.wait(0.5)
        clone = makeStaticAvatar(player)
    end

    if not clone then
        Status.Text = "Could not load avatar"
        return nil
    end

    clone.Parent = World
    currentModel = clone

    resetJoints(clone)
    rememberJointBases(clone)

    if not centerModel(clone) then
        clone:Destroy()
        currentModel = nil
        Status.Text = "Could not frame avatar"
        return nil
    end

    applyPose(clone, "N")
    Status.Text = "Avatar loaded"

    return clone
end

